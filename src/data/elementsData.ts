export function getElementParticleDetails(el: ElementData) {
  const p = el.number;
  const e = el.number;
  const massNumber = el.massNumber ?? (el.number === 17 ? 35 : Math.round(el.roundedMass));
  const n = el.neutrons ?? Math.max(0, massNumber - p);
  return {
    protons: p,
    neutrons: n,
    electrons: e,
    massNumber,
    isChlorineSpecial: el.number === 17,
    isHydrogenZeroNeutron: el.number === 1 && n === 0,
    noteVi: el.number === 17
      ? 'Đồng vị phổ biến ³⁵Cl (75.8% trong tự nhiên) có 18n; đồng vị ³⁷Cl (24.2%) có 20n. NTK trung bình làm tròn tính toán SGK là 35.5 amu.'
      : el.number === 1
      ? 'Đồng vị Protium (¹H, chiếm >99.98% trong tự nhiên) chỉ gồm 1 proton trong hạt nhân và 0 neutron.'
      : `Hạt nhân gồm ${p} proton (+${p}) và ${n} neutron (A = ${massNumber}); vỏ nguyên tử gồm ${e} electron xếp trên ${el.electronsPerShell.length} lớp vỏ.`
  };
}


